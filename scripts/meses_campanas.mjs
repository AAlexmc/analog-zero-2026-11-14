// ¿En qué mes fue NASA a cada análogo y qué mes se parece más según el motor mensual? Imprime una tabla Markdown.
// Uso: node scripts/meses_campanas.mjs > docs/meses-campanas.md
import { readFile } from 'node:fs/promises';
import { cargar } from '../web/buscar/motor.js';
import { parametrosDe } from '../web/analogos/misiones.js';
import { MESES_CORTO } from '../web/analogos/meses.js';

const raiz = new URL('../', import.meta.url);
const json = async (r) => JSON.parse(await readFile(new URL(r, raiz), 'utf8'));
const base = new URL('web/data/cuerpos/', raiz);
const leer = async (url, tipo) => { const b = await readFile(new URL(url, base)); return tipo === 'json' ? JSON.parse(b.toString('utf8')) : b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength); };
const M = await cargar('', leer);
await M.cargarMeses();
const { misiones } = await json('datos_json/misiones.json');
// Puntos de comparación (elección propia): Jezero para Marte; el mejor sitio que da la herramienta en el polo sur lunar.
const OBJETIVO = { mars: { nombre: 'Jezero crater', lat: 18.38, lon: 77.58 }, moon: { nombre: 'lunar south pole (89.45° S, 137.15° W)', lat: -89.45, lon: -137.15 } };
const soloTierra = new Set((M.indice.parametros_tierra ?? []).map((p) => p.id));
const mes = (m) => MESES_CORTO[m - 1];
const filas = [];
for (const mi of misiones) {
  const delPunto = parametrosDe(mi, M.indice).filter((id) => !soloTierra.has(id));
  for (const c of mi.campanas) {
    if (!c.meses?.length || c.lat === null || c.meses.length === 12) continue;
    for (const cuerpo of mi.cuerpo) {
      const o = OBJETIVO[cuerpo], obj = M.leerPunto(cuerpo, o.lat, o.lon);
      const opc = delPunto.length ? { parametros: delPunto } : {};
      const pf = M.perfilMensual(obj, { lat: c.lat, lon: c.lon }, opc);
      if (!pf) { filas.push({ mi, c, cuerpo, sin: true }); continue; }
      const v = pf.map((x) => x.similitud_pct);
      if (v.some((x) => !Number.isFinite(x))) { filas.push({ mi, c, cuerpo, sin: true }); continue; }
      const max = Math.max(...v), min = Math.min(...v);
      const enCampana = Math.max(...c.meses.map((m) => v[m - 1]));
      const mejores = v.map((x, i) => [x, i + 1]).filter(([x]) => max - x < 0.05).map(([, m]) => m);
      const puesto = 1 + v.filter((x) => x > enCampana + 1e-9).length;
      filas.push({ mi, c, cuerpo, n: pf[0].comparados, de: (delPunto.length || 8), max, min, enCampana, mejores, puesto });
    }
  }
}
// Solo cuentan los pares cuyo parecido cambia con el mes (los de solo terreno dan lo mismo todo el año).
const con = filas.filter((f) => !f.sin && f.max - f.min > 0.05);
const fijos = filas.filter((f) => !f.sin && f.max - f.min <= 0.05);
const cerca = con.filter((f) => f.max - f.enCampana <= 5).length;
const polares = con.filter((f) => Math.abs(f.c.lat) >= 60);
console.log('# When NASA went, and when the site is most alike\n');
console.log('Generated by `node scripts/meses_campanas.mjs` from `datos_json/misiones.json` (campaign months, each with its quoted source) and the monthly engine (`docs/metrica-analogos.md`, «Meses»). Own analysis.\n');
console.log(`Comparison points (own choice): ${OBJETIVO.mars.nombre} for Mars, ${OBJETIVO.moon.nombre} for the Moon. Only the parameters of each mission that are compared with that point are used (the Earth-only ones compare a site with itself). The Moon or Mars value stays at its yearly value. Climatology: the mean month over many years, not the year of the campaign.\n`);
console.log('| Mission | Campaign site | Compared with | NASA went in | Match then | Best month(s) | Match at best | Rank of NASA\'s month (of 12) | Yearly swing |');
console.log('|---|---|---|---|---|---|---|---|---|');
for (const f of filas) {
  const sitio = c2(f.c);
  if (f.sin) { console.log(`| ${f.mi.nombre} | ${sitio} | ${f.cuerpo === 'mars' ? 'Mars' : 'Moon'} | ${f.c.meses.map(mes).join(', ')} | no data at this cell | — | — | — | — |`); continue; }
  if (f.max - f.min <= 0.05) { console.log(`| ${f.mi.nombre} | ${sitio} | ${f.cuerpo === 'mars' ? 'Mars' : 'Moon'} | ${f.c.meses.map(mes).join(', ')} | ${f.enCampana.toFixed(1)} % | same all year | ${f.max.toFixed(1)} % | — | none: terrain parameters only |`); continue; }
  console.log(`| ${f.mi.nombre} | ${sitio} | ${f.cuerpo === 'mars' ? 'Mars' : 'Moon'} | ${f.c.meses.map(mes).join(', ')} | ${f.enCampana.toFixed(1)} % | ${f.mejores.map(mes).join(', ')} | ${f.max.toFixed(1)} % | ${f.puesto} | ${(f.max - f.min).toFixed(1)} points |`);
}
function c2(c) { return `${c.sitio_texto ?? c.sitio} (${c.lat.toFixed(2)}, ${c.lon.toFixed(2)})`; }
const mediana = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.floor((s.length - 1) / 2)] : NaN; };
console.log(`\n**Summary.** ${con.length} campaign-and-world pairs whose match changes with the month (${fijos.length} more use terrain parameters only and are the same all year). NASA's month is the site's best month in ${con.filter((f) => f.puesto === 1).length} of ${con.length}, and within 5 points of it (own threshold) in ${cerca}; median rank of NASA's month: ${mediana(con.map((f) => f.puesto))} of 12.`);
console.log(`\n**Polar sites (beyond 60° of latitude).** ${polares.length} pairs; rank of NASA's month: ${polares.map((f) => f.puesto).join(', ')} of 12; they lose ${Math.min(...polares.map((f) => f.max - f.enCampana)).toFixed(1)} to ${Math.max(...polares.map((f) => f.max - f.enCampana)).toFixed(1)} points against their best month. NASA went in local summer; by temperature and light these sites are most like the Moon or Mars in local winter.`);
console.log('\nLimits: this does not say NASA chose badly. The month of a campaign depends on access, daylight for the crews, budget and safety, none of which is measured here; and several of these tests (drills, radar, rover driving) do not need the coldest month. A 0.5° cell is not the campaign spot. A campaign that lasted the whole year is left out. The match is our own metric, not a probability.');
